import type { AgentSkill, AgentSkillParam } from './types'

/**
 * 内置技能目录（主进程运行时与渲染端技能库共用同一份）。
 *
 * 设计原则：一个人用邮件接收工作往来、账单订阅、订单物流、会议出行、通知验证码、资讯、
 * 招聘、政务银行保险……每个技能是一位资深助理的「工作说明」：
 * - 先查什么数据（按工具类别写：搜索邮件 / 读邮件理解 / 待办 / 财务汇总 / 项目时间线 /
 *   附件检索 / 知识库 / 记忆 / 联系人画像 / 日历忙碌），再如何判断，最后按固定格式输出；
 * - 所有写操作（归档、标记、建待办、记账、写知识库、退订、发信）只以「待确认动作」给出；
 * - 参数用 {{key}} 占位，运行时代入。
 *
 * 示例中的公司 / 人名一律虚构。
 */

/** 分类顺序（技能库分组、侧栏「更多技能」排序都按这个） */
export const SKILL_CATEGORIES = ['每日', '收件箱', '人脉', '项目', '财务', '资料', '出行', '写作', '生活事务', '自定义'] as const

/** 所有内置技能共用的输出与安全约定（追加在每条说明末尾，复制为自定义时一并带走，可删改） */
const RULES = `
【通用要求】
- 只依据工具查到的真实数据作答；查不到就直说「没有找到」，绝不编造邮件、金额、日期、单号或人名。
- 每条结论都附来源引用（邮件 / 待办 / 款项 / 项目 / 附件 / 知识库 / 记忆），方便用户点开核对。
- 中文，先结论后细节：一句话总览 → 分小节列表；单条不超过两行；没有内容的小节直接省略，不写「无」。
- 日期写成相对今天的说法并附具体日期，如「明天（10/19 周一）」「3 天前（10/15）」。
- 金额带币种，同币种才相加；不同币种分开列。
- 任何会改变数据或对外发送的操作（归档、标已读、加旗标、稍后处理、建待办、记账、写知识库、写记忆、退订、发信）只能作为「待确认动作」提出，由用户确认后执行；邮件只起草、不发送。
- 用户的语气、称呼、签名偏好以记忆里的「偏好」为准。`

const days = (def: number, label = '时间范围（天）'): AgentSkillParam => ({ key: 'days', label, kind: 'days', default: def })

function skill(s: Omit<AgentSkill, 'builtin'>): AgentSkill {
  return { ...s, instructions: `${s.instructions.trim()}\n${RULES}`, builtin: true }
}

